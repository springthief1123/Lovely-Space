/** 既存UIのAND/ORの機能比較用。これは単純な文字列包含で、実際の検索パーサではない。 */
internal object PocKeywordBaseline {
    fun terms(input: String): List<String> =
        input.split(',', '、', '，', '\n').map { it.trim() }.filter { it.isNotEmpty() }.distinct()

    fun isMatch(text: String, words: List<String>, requireAll: Boolean): Boolean {
        if (words.isEmpty()) return false
        return if (requireAll) words.all { text.contains(it, ignoreCase = true) }
        else words.any { text.contains(it, ignoreCase = true) }
    }

    fun matchedCount(texts: List<String>, words: List<String>, requireAll: Boolean): Int =
        texts.count { isMatch(it, words, requireAll) }
}
